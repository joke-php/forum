<?php

declare(strict_types=1);

namespace Vasoft\Joke\Forum\Contract;

/**
 * Интерфейс элемента меню.
 *
 * Определяет контракт для элементов навигационного меню, поддерживающих
 * иерархическую структуру через вложенные дочерние элементы.
 */
interface MenuItemInterface
{
    /**
     * @var string Стили пункта меню
     */
    public string $classList {
        get;
    }
    /**
     * URL-адрес, связанный с элементом меню.
     */
    public string $url {
        get;
    }
    /**
     * Название элемента меню.
     */
    public string $label {
        get;
    }
    /**
     * Флаг доступности элемента меню.
     *
     * Определяет, должен ли элемент отображаться в меню.
     * Отключенные элементы могут быть скрыты или отображены
     * в неактивном состоянии в зависимости от реализации компонента меню.
     */
    public bool $enabled {
        get;
    }
    /**
     * Дочерние элементы меню (вложенная структура).
     *
     * Возвращает массив вложенных элементов меню, реализующих MenuItemInterface.
     * Пустой массив означает отсутствие дочерних элементов.
     *
     * @var array<int, MenuItemInterface> Массив дочерних элементов меню
     */
    public array $children {
        get;
    }
}
